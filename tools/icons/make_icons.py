def rows(art):
    lines = [l for l in art.strip('\n').split('\n')]
    width = max(len(l) for l in lines)
    assert width <= 16, art
    return width, [sum(1 << (15 - i) for i, c in enumerate(l) if c == '#') for l in lines]

print('/* Icons for the menus, made by tools/icons/make_icons.py (the drawings are')
print(' * there). Rows have the leftmost pixel in bit 15. */')
print('#ifndef ICONS_H\n#define ICONS_H\n\n#include <stdint.h>\n')
print('struct Icon\n{\n    int w, h;\n    const uint16_t *rows;\n};\n')
names = list(ICONS)
for name in names:
    w, r = rows(ICONS[name])
    print('static const uint16_t icon_%s_rows[] = { %s };' % (name.lower(), ', '.join('0x%04x' % x for x in r)))
print()
print('enum IconId\n{\n    ICON_NONE,')
for name in names:
    print('    ICON_%s,' % name)
print('    NUM_ICONS\n};\n')
print('static const struct Icon icons[NUM_ICONS] =\n{\n    { 0, 0, 0 },')
for name in names:
    w, r = rows(ICONS[name])
    print('    { %d, %d, icon_%s_rows },' % (w, len(r), name.lower()))
print('};\n\n#endif')
